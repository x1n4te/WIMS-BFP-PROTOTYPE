# Run a Python helper from deploy/client/tools inside the backend image (no host Python/openssl).
function Invoke-Tool {
    param(
        [Parameter(Mandatory)][string]$Script,
        [string[]]$ScriptArgs = @(),
        [string[]]$Mounts = @(),
        [string[]]$ExtraDockerArgs = @()
    )
    $tools = Join-Path $script:Root 'tools'
    $dockerArgs = @('run', '--rm', '--user', 'root', '--entrypoint', 'python', '-v', "${tools}:/tools:ro") + $Mounts + $ExtraDockerArgs + @($script:BackendImage, "/tools/$Script") + $ScriptArgs
    Invoke-Native -Exe 'docker' -Arguments $dockerArgs
}

function Get-ContainerHealth([string]$Name) {
    $r = Invoke-Quiet -Exe 'docker' -Arguments @('inspect', '--format', '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}', $Name)
    if ($r.ExitCode -ne 0) { return 'missing' }
    return ($r.Output -join '').Trim()
}

function Wait-ContainersReady {
    param([string[]]$Names, [int]$TimeoutSeconds = 900)
    $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
    $pending = @($Names)
    while ($pending.Count -gt 0) {
        $still = @()
        foreach ($n in $pending) {
            $h = Get-ContainerHealth $n
            if ($h -eq 'healthy' -or $h -eq 'running') { Write-Host "  ready: $n ($h)" } else { $still += $n }
        }
        $pending = $still
        if ($pending.Count -eq 0) { break }
        if ((Get-Date) -gt $deadline) { Fail "Timed out waiting for: $($pending -join ', '). Run: docker compose logs <name>" }
        Start-Sleep -Seconds 5
    }
}

function Get-FileSha256([string]$Path) {
    return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToLowerInvariant()
}
