# Shared helpers for the WIMS-BFP client scripts. Dot-source it: . "$PSScriptRoot\common.ps1"
# Written for Windows PowerShell 5.1 and PowerShell 7 (no ?? / ternary / && / ||).
# NOTE: these scripts have been reviewed but NOT executed (no Windows/Docker host was available
# when they were written). DEPLOYMENT_TEST_CHECKLIST.md is the first thing to run.

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

$script:Root = $PSScriptRoot
$script:EnvFile = Join-Path $script:Root '.env'
$script:ComposeProject = 'wims'
$script:ComposeNetwork = 'wims_default'
$script:BackendImage = 'wims-backend:client'
$script:DefaultHost = 'wims.bfp.lan'

function Write-Step([string]$Message) {
    Write-Host ''
    Write-Host "==> $Message" -ForegroundColor Cyan
}

function Fail([string]$Message) {
    Write-Host "ERROR: $Message" -ForegroundColor Red
    throw $Message
}

function Assert-Docker {
    if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
        Fail 'The "docker" command was not found. Install Rancher Desktop (INSTALL.md, section 1) and start it first.'
    }
    $r = Invoke-Quiet -Exe 'docker' -Arguments @('info', '--format', '{{.ServerVersion}}')
    if ($r.ExitCode -ne 0) {
        Fail "Docker is installed but not running. Start Rancher Desktop and wait until it says it is running. ($($r.Output -join ' '))"
    }
    $r = Invoke-Quiet -Exe 'docker' -Arguments @('compose', 'version')
    if ($r.ExitCode -ne 0) {
        Fail 'The "docker compose" plugin is missing. Use Rancher Desktop with the dockerd (moby) engine.'
    }
}

function Test-ImageLoaded([string]$Image) {
    return ((Invoke-Quiet -Exe 'docker' -Arguments @('image', 'inspect', $Image)).ExitCode -eq 0)
}

# Run a native command and stop on a non-zero exit code (PowerShell does not do that itself).
function Invoke-Native {
    param([Parameter(Mandatory)][string]$Exe, [string[]]$Arguments)
    & $Exe @Arguments
    if ($LASTEXITCODE -ne 0) {
        Fail "Command failed ($LASTEXITCODE): $Exe $($Arguments -join ' ')"
    }
}

# Run a native command, capturing stdout+stderr WITHOUT throwing. Windows PowerShell 5.1 turns any
# stderr line of a native command into a terminating error when $ErrorActionPreference is 'Stop'
# and the stream is redirected with 2>&1, so every such call goes through here.
function Invoke-Quiet {
    param([Parameter(Mandatory)][string]$Exe, [string[]]$Arguments = @())
    $old = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        $out = & $Exe @Arguments 2>&1
        $code = $LASTEXITCODE
    } finally { $ErrorActionPreference = $old }
    return [pscustomobject]@{ Output = @($out | ForEach-Object { "$_" }); ExitCode = $code }
}

function Invoke-Compose {
    param([string[]]$Arguments)
    $base = @('compose', '--project-name', $script:ComposeProject, '--project-directory', $script:Root,
        '--env-file', $script:EnvFile, '-f', (Join-Path $script:Root 'docker-compose.yml'))
    Invoke-Native -Exe 'docker' -Arguments ($base + $Arguments)
}

# .env helpers -------------------------------------------------------------------------------

function Read-DotEnv([string]$Path = $script:EnvFile) {
    $map = @{}
    if (-not (Test-Path -LiteralPath $Path)) { return $map }
    foreach ($line in [System.IO.File]::ReadAllLines($Path)) {
        $t = $line.Trim()
        if ($t -eq '' -or $t.StartsWith('#')) { continue }
        $i = $t.IndexOf('=')
        if ($i -lt 1) { continue }
        $key = $t.Substring(0, $i).Trim()
        $val = $t.Substring($i + 1).Trim()
        if ($val.Length -ge 2 -and $val.StartsWith("'") -and $val.EndsWith("'")) {
            $val = $val.Substring(1, $val.Length - 2)
        }
        $map[$key] = $val
    }
    return $map
}

# Write UTF-8 WITHOUT a byte-order mark (docker compose rejects a BOM in .env).
function Write-DotEnv([System.Collections.IDictionary]$Values, [string]$Path = $script:EnvFile) {
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine('# Generated by setup-secrets.ps1. Contains secrets: do not email or share.')
    foreach ($k in $Values.Keys) {
        $v = [string]$Values[$k]
        [void]$sb.AppendLine("$k='$v'")
    }
    [System.IO.File]::WriteAllText($Path, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
}

function Set-DotEnvValue([string]$Key, [string]$Value) {
    $map = Read-DotEnv
    $map[$Key] = $Value
    Write-DotEnv $map
}

# Randomness -----------------------------------------------------------------------------------

function New-RandomBytes([int]$Count) {
    $bytes = New-Object byte[] $Count
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($bytes) } finally { $rng.Dispose() }
    return , $bytes
}

# Alphanumeric only: safe inside SQL, URLs and docker compose interpolation.
function New-RandomPassword([int]$Length = 32) {
    $chars = 'abcdefghijkmnopqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789'
    $bytes = New-RandomBytes ($Length * 2)
    $sb = New-Object System.Text.StringBuilder
    $i = 0
    while ($sb.Length -lt $Length) {
        # Rejection sampling avoids modulo bias: 256 - (256 % 57) = 228
        if ($bytes[$i] -lt 228) { [void]$sb.Append($chars[$bytes[$i] % $chars.Length]) }
        $i++
        if ($i -ge $bytes.Length) { $bytes = New-RandomBytes ($Length * 2); $i = 0 }
    }
    return $sb.ToString()
}

# base64 of 32 random bytes: the format utils/crypto.py expects for WIMS_MASTER_KEY.
function New-MasterKey { return [Convert]::ToBase64String((New-RandomBytes 32)) }

